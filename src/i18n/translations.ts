export function getPaymentLabel(method: PaymentMethod, lang: Language): string {
  if (method === 'CASH') return lang === 'gu' ? 'રોકડ' : 'Cash';
  if (method === 'UPI') return 'UPI';
  return lang === 'gu' ? 'ઉધાર' : 'Udhar';
}

